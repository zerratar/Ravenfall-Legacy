"""The website's quest words (RavenNest's /quests page): the game's English texts for quests, quest chains,
achievements, titles, medals, village stories, unlocks, stream quests and skill names, copied from
Assets/Scripts/Localization.cs into RavenNest's src/RavenNest.Blazor.Services/GameTexts.cs, so the page words things as the game does.

    python tools/website/export-quest-texts.py

Rerun after changing any of those texts in the game.
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "..", "..", "Assets", "Scripts", "Localization.cs")
TARGET = os.path.realpath(os.path.join(HERE, "..", "..", "..", "RavenNest", "src", "RavenNest.Blazor.Services", "GameTexts.cs"))
PREFIXES = ("UI_QUEST_", "UI_CHAIN_", "UI_ACHIEVEMENT_", "UI_TITLE_", "UI_MEDAL_", "UI_STORY_", "UI_UNLOCK_", "UI_SKILL_", "UI_STREAM_QUEST_", "UI_DAILY_", "UI_BOON_")
# the riddles' answers and the in-game window's own words are not needed on the page
SKIP = re.compile(r"^UI_(CHAIN|STORY)_.*_(ANSWER|WRONG|RIDDLE)(_\d+)?$|^UI_STORY_(TAB|HINT|INTRO|ALL|BEGIN|ONE_AT_A_TIME|LET_CHAT_VOTE|VOTING|ABANDON)$|^UI_QUEST_(TAVERN|WINDOW|TAB|LOADING|FAILED)")

text = open(SOURCE, encoding="utf-8-sig").read()
pattern = re.compile(r'^\s*public static string (UI_[A-Z0-9_]+)\s*=\s*("(?:[^"\\]|\\.)*")\s*;\s*$', re.M)
entries = [(k, v) for k, v in pattern.findall(text) if k.startswith(PREFIXES) and not SKIP.search(k)]

lines = [
    "using System.Collections.Generic;",
    "",
    "namespace RavenNest.Blazor.Services",
    "{",
    "    /// <summary>",
    "    /// The game's English words for quests, chains, achievements, titles, village stories, unlocks and skills, so the",
    "    /// website's quest page says things as the game does. Generated by the game's tools/website/export-quest-texts.py",
    "    /// from its Localization.cs; do not edit by hand.",
    "    /// </summary>",
    "    public static class GameTexts",
    "    {",
    "        private static readonly Dictionary<string, string> texts = new Dictionary<string, string>",
    "        {",
]
lines += ['            ["%s"] = %s,' % (k, v) for k, v in entries]
lines += [
    "        };",
    "",
    "        /// <summary>A text by its name in the game (\"UI_CHAIN_CAT\"), any case; the fallback when there is none.</summary>",
    "        public static string Get(string name, string fallback = null) =>",
    "            name != null && texts.TryGetValue(name.ToUpperInvariant(), out var value) ? value : fallback;",
    "    }",
    "}",
    "",
]
with open(TARGET, "w", encoding="utf-8", newline="\r\n") as f:
    f.write("\n".join(lines))
print(len(entries), "texts to", TARGET)
